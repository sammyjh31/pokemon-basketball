import { POKEMON_BY_ID } from "../data/pokemon";
import type {
  BasketballMove,
  MoveOpportunity,
  SignatureEffects,
} from "./moveTypes";
type Focus = BasketballMove["focus"];
function typed(
  type: string,
  name: string,
  focus: Focus,
  opportunities: MoveOpportunity[],
  effects: SignatureEffects,
  cost: number,
  cooldown: number,
  zones?: BasketballMove["zones"],
): BasketballMove {
  return {
    id: `type-${type}` as BasketballMove["id"],
    name,
    focus,
    opportunities,
    effects,
    cost,
    cooldown,
    description: `${type[0].toUpperCase() + type.slice(1)}-type basketball technique; improves ${focus} actions with a timed energy cost.`,
    signature: { kind: "type", type, minimumMastery: 25 },
    ...(zones ? { zones } : {}),
  };
}
function species(
  id: BasketballMove["id"],
  name: string,
  ids: number[],
  focus: Focus,
  opportunities: MoveOpportunity[],
  effects: SignatureEffects,
  cost: number,
  cooldown: number,
  zones?: BasketballMove["zones"],
): BasketballMove {
  return {
    id,
    name,
    focus,
    opportunities,
    effects,
    cost,
    cooldown,
    description: `${ids.map((id) => POKEMON_BY_ID.get(id)!.name).join(" / ")} basketball signature; builds on this player's characteristic tools.`,
    signature: { kind: "species", speciesIds: ids, minimumMastery: 100 },
    ...(zones ? { zones } : {}),
  };
}
