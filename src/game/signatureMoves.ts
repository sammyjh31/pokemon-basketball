export function signatureMovesForSpecies(id: number): BasketballMove[] {
  const mon = POKEMON_BY_ID.get(id);
  if (!mon) return [];
  return signatureMoves.filter((move) =>
    move.signature!.kind === "type"
      ? mon.types.includes(move.signature!.type!)
      : move.signature!.speciesIds!.includes(id),
  );
}
