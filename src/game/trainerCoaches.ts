const byId = new Map(COACHES.map((c) => [c.id, c]));
export const getCoach = (id: string) => byId.get(id);
export function validateCoach(value: unknown): CoachAssignment | undefined {
  if (!value || typeof value !== "object") return;
  const v = value as Partial<CoachAssignment>;
  return v.version === 1 && typeof v.id === "string" && byId.has(v.id)
    ? { version: 1, id: v.id }
    : undefined;
}
function shuffled(seed: number) {
  const pool = [...COACHES];
  let state = (seed ^ 0x434f4143) >>> 0;
  for (let i = pool.length - 1; i > 0; i--) {
    const r = nextRandom(state);
    state = r.seed;
    const j = Math.floor(r.value * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool;
}
export const coachOffers = (seed: number) => shuffled(seed).slice(0, 3);
export function assignLeagueCoaches(
  teams: LeagueTeam[],
  seed: number,
  selected: ReadonlyMap<number, CoachAssignment>,
): LeagueTeam[] {
  const taken = new Set<string>();
  for (const [teamId, coach] of selected) {
    if (
      !teams.some((t) => t.id === teamId) ||
      !validateCoach(coach) ||
      taken.has(coach.id)
    )
      throw new Error("Invalid or duplicate trainer coach.");
    taken.add(coach.id);
  }
  const pool = shuffled(seed).filter((c) => !taken.has(c.id));
  if (pool.length < teams.length - selected.size)
    throw new Error("Not enough available coaches.");
  return teams.map((t) => ({
    ...t,
    coach: selected.get(t.id) ?? { version: 1, id: pool.shift()!.id },
  }));
}
